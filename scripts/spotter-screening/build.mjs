import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const sourceDirectory = new URL("./", import.meta.url);
const destination = process.argv[2] ?? fileURLToPath(new URL("../../js/vendor/spotter-screening/runtime-v1.js", sourceDirectory));

await build({
  absWorkingDir: fileURLToPath(sourceDirectory),
  entryPoints: ["browser.mjs"],
  outfile: destination,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["chrome110", "safari16"],
  minify: true,
  legalComments: "eof",
  banner: { js: "// Generated by scripts/spotter-screening/build.mjs. See LICENSES.txt for notices." },
});
